<#
.SYNOPSIS
  Undo what install.ps1 placed in the user profile (PowerShell 5.1 and 7).

.DESCRIPTION
  ASCII-only on purpose (Windows PowerShell 5.1 reads BOM-less scripts as cp949).

  Steps:
    link      remove %LOCALAPPDATA%\nvim ONLY if it is a junction/symlink that points
              at this repository's nvim folder. The link is deleted non-recursively
              ([IO.Directory]::Delete(path, $false)); the repository files are not touched.
              Then, if nothing is at %LOCALAPPDATA%\nvim, the newest nvim.bak-* backup
              made by install.ps1 is renamed back.
    neovide   remove %APPDATA%\neovide\config.toml only if it carries the install.ps1
              marker line; then restore the newest config.toml.bak-* if there is one.
    prestart  remove the Startup-folder shortcut work-kb-nvim-server.lnk if it points
              at nvim\bin\nvim-server.ps1. A server that is already running is left
              running (quit it with :qa from Neovide or reboot).
    purge     only with -Purge: delete the plugin folders named in nvim\lazy-lock.json
              (nvim-data\lazy\<name>) and the mason packages named in nvim\tools.lock.json
              (nvim-data\mason\packages\<name> and their bin links). Other plugins in
              nvim-data are left alone, because another Neovim config may share them.

  Never touched: nvim\lua\local.lua, .venv, the vault, scoop packages.
  -WhatIf prints every action and changes nothing.

.EXAMPLE
  powershell -NoProfile -ExecutionPolicy Bypass -File uninstall.ps1 -WhatIf
#>
[CmdletBinding(SupportsShouldProcess = $true)]
param(
    [switch]$Purge,
    [string]$LocalAppData = '',
    [string]$AppData = '',
    [string]$StartupDir = ''
)

Set-StrictMode -Version 2.0
$ErrorActionPreference = 'Stop'
$script:Cmdlet = $PSCmdlet
$script:Utf8NoBom = New-Object System.Text.UTF8Encoding $false
try { [Console]::OutputEncoding = $script:Utf8NoBom } catch { }

$ShortcutName = 'work-kb-nvim-server.lnk'
$MarkerPrefix = '# work-kb: generated by install.ps1'

$RepoRoot = Split-Path -Parent $MyInvocation.MyCommand.Path
$NvimDir = Join-Path $RepoRoot 'nvim'
if (-not $LocalAppData) { $LocalAppData = $env:LOCALAPPDATA }
if (-not $AppData) { $AppData = $env:APPDATA }
if (-not $StartupDir) { $StartupDir = [Environment]::GetFolderPath('Startup') }
if ($env:XDG_DATA_HOME) { $DataDir = Join-Path $env:XDG_DATA_HOME 'nvim-data' } else { $DataDir = Join-Path $LocalAppData 'nvim-data' }

$script:Results = New-Object System.Collections.ArrayList
function Out-Line([string]$Text) { [Console]::Out.WriteLine($Text) }
function Report([string]$Step, [string]$Status, [string]$Detail) {
    [void]$script:Results.Add([pscustomobject]@{ Step = $Step; Status = $Status; Detail = $Detail })
    Out-Line ('STEP {0} {1} {2}' -f $Step, $Status, $Detail)
}
function Test-WhatIf { return [bool]$WhatIfPreference }
function Invoke-Action([string]$Step, [string]$Description, [scriptblock]$Action) {
    if ($script:Cmdlet.ShouldProcess($Description, $Step)) {
        Out-Line ('  do: ' + $Description)
        & $Action | Out-Null
        return $true
    }
    if (Test-WhatIf) { Out-Line ('WHATIF {0} {1}' -f $Step, $Description) }
    else { Out-Line ('  declined: ' + $Description) }
    return $false
}
function Read-Utf8([string]$Path) { return [IO.File]::ReadAllText($Path, $script:Utf8NoBom) }
function Get-NormPath([string]$Path) { return ([IO.Path]::GetFullPath($Path)).TrimEnd('\') }
function Test-ReparsePoint([string]$Path) {
    $item = Get-Item -LiteralPath $Path -Force
    return (($item.Attributes -band [IO.FileAttributes]::ReparsePoint) -ne 0)
}
function Get-LinkTarget([string]$Path) {
    $item = Get-Item -LiteralPath $Path -Force
    $t = @($item.Target) | Where-Object { $_ } | Select-Object -First 1
    if (-not $t) { return $null }
    $t = [string]$t
    if ($t.StartsWith('\??\')) { $t = $t.Substring(4) }
    if (-not [IO.Path]::IsPathRooted($t)) { $t = Join-Path (Split-Path -Parent $Path) $t }
    return $t
}
function Get-NewestBackup([string]$Dir, [string]$Name) {
    if (-not (Test-Path -LiteralPath $Dir -PathType Container)) { return $null }
    $b = Get-ChildItem -LiteralPath $Dir -Force | Where-Object { $_.Name.StartsWith($Name + '.bak-') } | Sort-Object Name -Descending | Select-Object -First 1
    if ($b) { return $b.FullName }
    return $null
}

# Deletes a folder tree without ever following a junction or symlink inside it.
function Remove-TreeSafe([string]$Path) {
    $item = Get-Item -LiteralPath $Path -Force
    if (($item.Attributes -band [IO.FileAttributes]::ReparsePoint) -ne 0) {
        if ($item.PSIsContainer) { [IO.Directory]::Delete($Path, $false) } else { [IO.File]::Delete($Path) }
        return
    }
    if (-not $item.PSIsContainer) {
        $item.Attributes = [IO.FileAttributes]::Normal
        [IO.File]::Delete($Path)
        return
    }
    foreach ($child in @(Get-ChildItem -LiteralPath $Path -Force)) { Remove-TreeSafe $child.FullName }
    [IO.Directory]::Delete($Path, $false)
}

function Step-link {
    $link = Join-Path $LocalAppData 'nvim'
    $removed = $false
    if (Test-Path -LiteralPath $link) {
        if (-not (Test-ReparsePoint $link)) { Report 'link' 'skipped' ($link + ' is a real folder or file, not the install.ps1 junction; left alone'); return }
        $current = Get-LinkTarget $link
        if (-not $current -or ((Get-NormPath $current) -ine (Get-NormPath $NvimDir))) {
            Report 'link' 'skipped' ($link + ' points to ' + $current + ', not ' + $NvimDir + '; left alone'); return
        }
        $removed = Invoke-Action 'link' ('remove junction ' + $link + ' (non-recursive; ' + $NvimDir + ' is kept)') {
            if (-not (Test-ReparsePoint $link)) { throw ($link + ' is no longer a reparse point') }
            [IO.Directory]::Delete($link, $false)
        }
    }
    $backup = Get-NewestBackup $LocalAppData 'nvim'
    $restored = $false
    if ($backup -and ($removed -or (Test-WhatIf) -or -not (Test-Path -LiteralPath $link))) {
        $restored = Invoke-Action 'link' ('restore ' + $backup + ' -> ' + $link) { [IO.Directory]::Move($backup, $link) }
    }
    if (Test-WhatIf) { Report 'link' 'whatif' $link; return }
    if (-not $removed -and -not $restored) { Report 'link' 'ok' ('nothing to remove at ' + $link); return }
    $detail = ''
    if ($removed) { $detail = 'removed junction ' + $link }
    if ($restored) { $detail += '; restored ' + $backup }
    Report 'link' 'changed' $detail.TrimStart(';', ' ')
}

function Step-neovide {
    $dir = Join-Path $AppData 'neovide'
    $dest = Join-Path $dir 'config.toml'
    $removed = $false
    if (Test-Path -LiteralPath $dest -PathType Leaf) {
        if (-not (Read-Utf8 $dest).StartsWith($MarkerPrefix)) { Report 'neovide' 'skipped' ($dest + ' was not generated by install.ps1; left alone'); return }
        $removed = Invoke-Action 'neovide' ('remove ' + $dest) { [IO.File]::Delete($dest) }
    }
    $backup = Get-NewestBackup $dir 'config.toml'
    $restored = $false
    if ($backup -and ($removed -or (Test-WhatIf) -or -not (Test-Path -LiteralPath $dest))) {
        $restored = Invoke-Action 'neovide' ('restore ' + $backup + ' -> ' + $dest) { [IO.File]::Move($backup, $dest) }
    }
    if (Test-WhatIf) { Report 'neovide' 'whatif' $dest; return }
    if (-not $removed -and -not $restored) { Report 'neovide' 'ok' ('nothing to remove at ' + $dest); return }
    $detail = ''
    if ($removed) { $detail = 'removed ' + $dest }
    if ($restored) { $detail += '; restored ' + $backup }
    Report 'neovide' 'changed' $detail.TrimStart(';', ' ')
}

function Step-prestart {
    $lnk = Join-Path $StartupDir $ShortcutName
    if (-not (Test-Path -LiteralPath $lnk)) { Report 'prestart' 'ok' ('no shortcut at ' + $lnk); return }
    $shell = New-Object -ComObject WScript.Shell
    $args0 = [string]$shell.CreateShortcut($lnk).Arguments
    if ($args0 -notmatch 'nvim-server\.ps1') { Report 'prestart' 'skipped' ($lnk + ' was not created by install.ps1; left alone'); return }
    $done = Invoke-Action 'prestart' ('remove ' + $lnk) { [IO.File]::Delete($lnk) }
    if (Test-WhatIf) { Report 'prestart' 'whatif' $lnk; return }
    if ($done) { Report 'prestart' 'changed' ('removed ' + $lnk + ' (a running server keeps running until you quit it)') } else { Report 'prestart' 'skipped' 'declined' }
}

function Get-JsonNames([string]$Path, [switch]$Tools) {
    if (-not (Test-Path -LiteralPath $Path -PathType Leaf)) { return @() }
    $data = Read-Utf8 $Path | ConvertFrom-Json
    if ($Tools -and $data -isnot [array] -and $data.PSObject.Properties['tools']) { $data = $data.tools }
    if ($data -is [array]) { return @($data | ForEach-Object { $s = [string]$_; $i = $s.LastIndexOf('@'); if ($i -gt 0) { $s.Substring(0, $i) } else { $s } }) }
    return @($data.PSObject.Properties | Where-Object { -not $_.Name.StartsWith('_') -and -not $_.Name.StartsWith('$') } | ForEach-Object { $_.Name })
}

function Step-purge {
    if (-not $Purge) { Report 'purge' 'skipped' 'use -Purge to delete the locked plugins and mason tools'; return }
    $targets = @()
    foreach ($name in (Get-JsonNames (Join-Path $NvimDir 'lazy-lock.json'))) {
        if ($name -match '[\\/]|^\.\.?$') { continue }
        $p = Join-Path $DataDir ('lazy\' + $name)
        if (Test-Path -LiteralPath $p) { $targets += $p }
    }
    foreach ($name in (Get-JsonNames (Join-Path $NvimDir 'tools.lock.json') -Tools)) {
        if ($name -match '[\\/]|^\.\.?$') { continue }
        $pkg = Join-Path $DataDir ('mason\packages\' + $name)
        if (-not (Test-Path -LiteralPath $pkg)) { continue }
        $receipt = Join-Path $pkg 'mason-receipt.json'
        if (Test-Path -LiteralPath $receipt -PathType Leaf) {
            try {
                $r = Read-Utf8 $receipt | ConvertFrom-Json
                if ($r.PSObject.Properties['links'] -and $r.links.PSObject.Properties['bin']) {
                    foreach ($b in $r.links.bin.PSObject.Properties) {
                        $bp = Join-Path $DataDir ('mason\bin\' + $b.Name)
                        if (Test-Path -LiteralPath $bp) { $targets += $bp }
                    }
                }
            } catch { }
        }
        $targets += $pkg
    }
    if ($targets.Count -eq 0) { Report 'purge' 'ok' 'nothing to delete'; return }
    $n = 0
    foreach ($t in $targets) {
        if (Invoke-Action 'purge' ('delete ' + $t) { Remove-TreeSafe $t }) { $n++ }
    }
    if (Test-WhatIf) { Report 'purge' 'whatif' ('' + $targets.Count + ' item(s)'); return }
    Report 'purge' 'changed' ('deleted ' + $n + ' item(s)')
}

Out-Line ('work-kb uninstall: repo ' + $RepoRoot)
if (-not $LocalAppData -or -not $AppData) { Out-Line 'LOCALAPPDATA/APPDATA not set'; exit 2 }
if (Test-WhatIf) { Out-Line '  -WhatIf: nothing will be changed' }
foreach ($step in 'link', 'neovide', 'prestart', 'purge') {
    try { & ('Step-' + $step) } catch { Report $step 'failed' ('error: ' + $_.Exception.Message) }
}
$failedCount = @($script:Results | Where-Object { $_.Status -eq 'failed' }).Count
if ($failedCount -gt 0) { exit 1 }
exit 0
