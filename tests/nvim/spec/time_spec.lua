-- 시각 형식 (캡처 HH:MM, daily 날짜, 자산·inbox·클립보드 이름, inbox created).
local H = require("helpers")

describe("time", function()
  it("now()는 setup의 now 이음매를 쓴다", function()
    H.configure()
    local time = require("work-kb.time")
    H.eq(time.now(), H.TIME)
    H.configure({ now = false })
    H.ok(math.abs(time.now() - os.time()) <= 2, "이음매가 없으면 os.time()")
  end)

  it("고정 시각 2026-11-05 09:12:00의 형식들", function()
    H.configure()
    local time = require("work-kb.time")
    H.eq(time.day(), "2026-11-05")
    H.eq(time.hhmm(), "09:12")
    H.eq(time.asset_stamp(), "2026-11-05-0912")
    H.eq(time.inbox_stamp(), "20261105-0912")
    H.eq(time.clip_stamp(), "20261105-091200")
    local iso = time.iso()
    H.ok(iso:match("^2026%-11%-05T09:12:00[+-]%d%d:%d%d$"), "iso: " .. iso)
    H.eq(time.format("%Y%%%H"), "2026%09")
  end)

  it("오프셋은 OS 로컬 시간대와 맞다", function()
    local time = require("work-kb.time")
    local t = H.TIME
    local off = time.offset(t)
    local sign, hh, mm = off:match("^([+-])(%d%d):(%d%d)$")
    H.ok(sign, "형식: " .. off)
    local seconds = (tonumber(hh) * 3600 + tonumber(mm) * 60) * (sign == "-" and -1 or 1)
    local utc = os.date("!*t", t)
    utc.isdst = os.date("*t", t).isdst
    H.eq(seconds, os.difftime(t, os.time(utc)))
  end)

  it("모르는 형식 지정자는 strftime에 넘기지 않고 오류", function()
    local time = require("work-kb.time")
    H.fails_with(function()
      time.format("%Q", H.TIME)
    end)
  end)
end)
