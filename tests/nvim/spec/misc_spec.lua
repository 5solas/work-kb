-- l (link), ? (status) — ERT work-kb-test-link-and-status-args + 메시지. :checkhealth도 한 번.
local H = require("helpers")

describe("misc", function()
  it("link·status 인수: <명령> --root <볼트>", function()
    local vault = H.with_vault({ python = H.python() })
    H.ui_stub()
    local fake = H.fake_spawn({ code = 0 })
    local misc = require("work-kb.misc")
    local proc = require("work-kb.proc")
    proc.wait(misc.link(), 5000)
    proc.wait(misc.status(), 5000)
    H.eq(#fake.calls, 2)
    H.eq(fake.calls[1].argv, { "link", "--root", vault })
    H.eq(fake.calls[2].argv, { "status", "--root", vault })
  end)

  it("link 메시지: 요약(마지막 줄) / 완료 / 실패 (종료 N), 버퍼를 보인다", function()
    H.with_vault({ python = H.python() })
    local stub = H.ui_stub()
    local misc = require("work-kb.misc")
    local proc = require("work-kb.proc")
    H.fake_spawn({ code = 0, output = "원천 7개\n언급 43건, 새 페이지 8\n" })
    local handle = misc.link()
    proc.wait(handle, 5000)
    H.eq(stub.messages[1], "work-kb link: 언급 43건, 새 페이지 8")
    H.eq(stub.shown[1], handle.bufnr)
    H.eq(proc.buffer_name(handle.bufnr), "*work-kb*")
    H.fake_spawn({ code = 0, output = "" })
    proc.wait(misc.link(), 5000)
    H.eq(stub.messages[2], "work-kb link: 완료")
    H.fake_spawn({ code = 6, output = "오류: 잠김\n" })
    proc.wait(misc.link(), 5000)
    H.eq(stub.messages[3], "work-kb link 실패 (종료 6)")
    H.eq(#stub.shown, 3)
  end)

  it("status: 버퍼를 보이고 실패만 알린다", function()
    H.with_vault({ python = H.python() })
    local stub = H.ui_stub()
    local misc = require("work-kb.misc")
    local proc = require("work-kb.proc")
    H.fake_spawn({ code = 0, output = "마지막 동기화: 없음\r\n" })
    local handle = misc.status()
    proc.wait(handle, 5000)
    H.eq(#stub.messages, 0)
    H.eq(stub.shown, { handle.bufnr })
    H.eq(H.buffer_text(), "마지막 동기화: 없음\n")
    H.fake_spawn({ code = 4, output = "오류\n" })
    proc.wait(misc.status(), 5000)
    H.eq(stub.messages, { "work-kb status 실패 (종료 4)" })
  end)

  it("실제 kb.py status (한 번 실행)는 0으로 끝나고 볼트를 읽는다", function()
    local auto = H.exists(H.repo .. "/.venv/Scripts/python.exe")
    local vault = H.with_vault({ python = (not auto) and H.python() or nil })
    H.copy_config(vault)
    local stub = H.ui_stub()
    local proc = require("work-kb.proc")
    local handle = require("work-kb.misc").status()
    H.eq(proc.wait(handle, 60000), 0, "출력: " .. tostring(H.buffer_text()))
    H.eq(#stub.messages, 0)
    H.ok(#H.buffer_text() > 0, "status 출력이 비었음")
    H.not_contains(H.buffer_text(), "\r")
    H.ok(vault)
  end)

  it("ui: 실제 동기 입력 (input·select·confirm, 미리 넣은 키로)", function()
    local ui = require("work-kb.ui")
    local function typed(keys, fn)
      vim.api.nvim_feedkeys(vim.keycode(keys), "t", false)
      return fn()
    end
    H.eq(typed("답 😀<CR>", function()
      return ui.input("제목: ")
    end), "답 😀")
    H.eq(typed("<CR>", function()
      return ui.input("제목: ", { default = "기본값" })
    end), "기본값")
    H.eq(typed("<CR>", function()
      return ui.input("댓글: ", { initial = "현재 줄" })
    end), "현재 줄")
    H.eq(typed("<Esc>", function()
      return ui.input("취소: ")
    end), nil)
    H.eq(typed("cap<Tab><CR>", function()
      return ui.select("유형: ", { "capture", "zzz" })
    end), "capture")
    H.eq(typed("<CR>", function()
      return ui.select("유형: ", { "Task", "Bug" }, { default = "Task" })
    end), "Task")
    H.eq(typed("2<CR>", function()
      return ui.select("전환: ", { "진행 중", "완료" }, { strict = true })
    end), "완료")
    H.eq(typed("9<CR>", function()
      return ui.select("전환: ", { "진행 중", "완료" }, { strict = true })
    end), nil)
    H.eq(typed("y", function()
      return ui.confirm("전환할까요? ")
    end), true)
    H.eq(typed("n", function()
      return ui.confirm("전환할까요? ")
    end), false)
    local buf = vim.api.nvim_create_buf(false, true)
    local before = vim.api.nvim_get_current_win()
    local win = ui.show(buf)
    H.ok(win and vim.api.nvim_win_is_valid(win))
    H.eq(vim.api.nvim_get_current_win(), before, "초점을 옮기지 않는다")
    H.eq(ui.show(buf), win, "이미 보이면 그 창")
    vim.api.nvim_win_close(win, true)
    H.fails_with(function()
      ui.fail("사용자 오류 문구")
    end, "사용자 오류 문구")
    H.ok(ui.is_user_error("사용자 오류 문구"))
    H.ok(not ui.is_user_error("다른 오류"))
  end)

  it(":checkhealth work-kb가 오류 없이 돈다", function()
    H.with_vault({ python = H.python() })
    vim.cmd("checkhealth work-kb")
    local text = table.concat(vim.api.nvim_buf_get_lines(0, 0, -1, false), "\n")
    H.contains(text, "work-kb")
    H.contains(text, "코드 루트")
    H.not_contains(text, "Failed to run healthcheck")
    vim.cmd("bwipeout!")
  end)
end)
